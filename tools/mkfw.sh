# Generates a C file embedding the ZD1211 firmware images.
# usage: mkfw.sh <firmware dir> <output .c>
set -eu
dir=$1
out=$2
{
	echo '/* Generated by tools/mkfw.sh from firmware/ - do not edit. */'
	echo '/* The firmware images are distributed under the GNU GPL, see firmware/COPYING. */'
	echo '#include <string.h>'
	echo '#include "fw.h"'
	for f in zd1211_ub zd1211_ur zd1211_uphr zd1211b_ub zd1211b_ur zd1211b_uphr; do
		echo "static const uint8_t fw_${f}[] = {"
		/usr/bin/xxd -i < "$dir/$f"
		echo '};'
	done
	echo 'const struct zd_fw *zd_fw_get(int is_zd1211b, const char *postfix)'
	echo '{'
	echo '	static const struct zd_fw fws[2][3] = {'
	echo '		{ { fw_zd1211_ub, sizeof(fw_zd1211_ub) }, { fw_zd1211_ur, sizeof(fw_zd1211_ur) }, { fw_zd1211_uphr, sizeof(fw_zd1211_uphr) } },'
	echo '		{ { fw_zd1211b_ub, sizeof(fw_zd1211b_ub) }, { fw_zd1211b_ur, sizeof(fw_zd1211b_ur) }, { fw_zd1211b_uphr, sizeof(fw_zd1211b_uphr) } },'
	echo '	};'
	echo '	int i;'
	echo '	if (!strcmp(postfix, "ub")) i = 0;'
	echo '	else if (!strcmp(postfix, "ur")) i = 1;'
	echo '	else if (!strcmp(postfix, "uphr")) i = 2;'
	echo '	else return NULL;'
	echo '	return &fws[is_zd1211b ? 1 : 0][i];'
	echo '}'
} > "$out"
